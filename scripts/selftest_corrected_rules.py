#!/usr/bin/env python3
"""corrected_rules.py の逆テスト。

訂正済みデータセットの規則は、誤りと確定できる値だけを直し、それ以外は元の値を
残して注記する。ここでは規則の表の各行に1件ずつ対応させ、
「直す」「空欄にする」「残して注記する」「何もしない」を取り違えていないことを固定する。

注記には元の値をそのまま含める。validate_corrected.py はそれを手がかりに、
値が変わったセルに説明があるかを確かめる。
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from corrected_rules import (closed_date_notes, decide_coord, fix_time,  # noqa: E402
                             fix_url, time_pairs)


def main():
    cases = [
        # 時刻の列の組
        ("診療科の票の列を組にする",
         time_pairs(["ID", "月_診療開始時間", "月_診療終了時間",
                     "月_外来受付開始時間", "月_外来受付終了時間"]),
         [("月_診療開始時間", "月_診療終了時間", "月_診療"),
          ("月_外来受付開始時間", "月_外来受付終了時間", "月_外来受付")]),
        ("時間帯の番号を持つ列を組にする",
         time_pairs(["祝_開店時間帯2_開始時間", "祝_開店時間帯2_終了時間"]),
         [("祝_開店時間帯2_開始時間", "祝_開店時間帯2_終了時間", "祝_開店時間帯2")]),
        ("曜日で始まらない列は組にしない",
         time_pairs(["診療時間帯", "ID"]), []),

        # 時刻
        ("開始と終了が同じ区間は空欄にする",
         fix_time("17:00", "17:00", "火_診療"),
         ("", "", "空欄にした: 火_診療 17:00-17:00（開始と終了が同じ）")),
        ("00:00-00:00 も空欄にする",
         fix_time("00:00", "00:00", "月_外来受付"),
         ("", "", "空欄にした: 月_外来受付 00:00-00:00（開始と終了が同じ）")),
        ("06:00 より前の開始は残して注記する",
         fix_time("00:45", "17:15", "火_診療"),
         ("00:45", "17:15", "疑い: 火_診療 00:45-17:15（開始が 06:00 より前）")),
        ("23:00 より後の終了は残して注記する",
         fix_time("09:00", "23:30", "月_外来受付"),
         ("09:00", "23:30", "疑い: 月_外来受付 09:00-23:30（終了が 23:00 より後）")),
        ("18時間以上の日跨ぎは残して注記する",
         fix_time("15:30", "15:00", "火_外来受付"),
         ("15:30", "15:00", "疑い: 火_外来受付 15:30-15:00（日跨ぎとしても 18時間以上）")),
        ("ちょうど18時間の日跨ぎも残して注記する",
         fix_time("15:00", "09:00", "金_診療"),
         ("15:00", "09:00", "疑い: 金_診療 15:00-09:00（日跨ぎとしても 18時間以上）")),
        ("00:00-23:59 は何もしない",
         fix_time("00:00", "23:59", "水_診療"), ("00:00", "23:59", "")),
        ("18時間未満の日跨ぎは何もしない",
         fix_time("17:00", "09:00", "金_診療"), ("17:00", "09:00", "")),
        ("通常の区間は何もしない",
         fix_time("09:00", "17:00", "月_診療"), ("09:00", "17:00", "")),
        ("空欄は何もしない",
         fix_time("", "", "月_診療"), ("", "", "")),

        # その他の休診日
        ("31日を超える範囲は注記する",
         closed_date_notes("8/14-5/16", "その他の休診日（gw、お盆等）"),
         ["疑い: その他の休診日（gw、お盆等） 8/14-5/16（範囲が31日を超える。終点の打ち間違いの疑い）"]),
        ("31日以内の範囲は注記しない",
         closed_date_notes("12月29日～1月3日", "その他の休診日（gw、お盆等）"), []),
        ("日付を特定できない記述は注記しない",
         closed_date_notes("GW、お盆", "その他の休診日（gw、お盆等）"), []),
        ("空欄は注記しない",
         closed_date_notes("", "その他の休診日（gw、お盆等）"), []),

        # URL
        ("コロンの脱字は補う",
         fix_url("http//www.example.jp", "ホームページアドレス"),
         ("http://www.example.jp",
          "書き換えた: ホームページアドレス http//www.example.jp → http://www.example.jp（コロンの脱字）")),
        ("検索エンジンの転送 URL は空欄にする",
         fix_url("https://www.bing.com/ck/a?u=x", "ホームページアドレス"),
         ("", "空欄にした: ホームページアドレス https://www.bing.com/ck/a?u=x（検索エンジンの転送 URL）")),
        ("スキームが無ければ残して注記する",
         fix_url("example.jp", "ホームページアドレス"),
         ("example.jp", "疑い: ホームページアドレス example.jp（スキームが無い）")),
        ("スラッシュが1本なら残して注記する",
         fix_url("http:/www.example.jp/", "ホームページアドレス"),
         ("http:/www.example.jp/", "疑い: ホームページアドレス http:/www.example.jp/（URL として読めない形式）")),
        ("300文字を超えても何もしない",
         fix_url("https://example.jp/" + "a" * 300, "ホームページアドレス"),
         ("https://example.jp/" + "a" * 300, "")),
        ("正しい URL は何もしない",
         fix_url("https://example.jp/", "ホームページアドレス"), ("https://example.jp/", "")),
        ("空欄は何もしない",
         fix_url("", "ホームページアドレス"), ("", "")),

        # 座標
        ("元データの座標を使う行はそのまま残す",
         decide_coord("43.055405", "141.333497",
                      {"ID": "H001", "座標の出典": "原データ", "元_緯度": "43.055405",
                       "元_経度": "141.333497", "座標の理由": "",
                       "住所_lat": "43.056339", "住所_lon": "141.33299", "住所_位置レベル": "3"},
                      None),
         ("43.055405", "141.333497", "原データ", "")),
        ("0,0 は住居表示の点で置き換える",
         decide_coord("0.0", "0.0",
                      {"ID": "H002", "座標の出典": "ジオコーディング", "元_緯度": "0.0",
                       "元_経度": "0.0", "座標の理由": "",
                       "住所_lat": "43.069891362", "住所_lon": "141.334289858",
                       "住所_位置レベル": "8"},
                      None),
         ("43.069891362", "141.334289858", "住居表示",
          "書き換えた: 緯度経度 0.0, 0.0 → 住居表示の点（欠損を示す値）")),
        ("住居表示の点が無ければ地番の点で置き換える",
         decide_coord("0.0", "0.0",
                      {"ID": "H003", "座標の出典": "なし", "元_緯度": "0.0", "元_経度": "0.0",
                       "座標の理由": "", "住所_lat": "", "住所_lon": "", "住所_位置レベル": ""},
                      ("43.1", "141.4")),
         ("43.1", "141.4", "地番",
          "書き換えた: 緯度経度 0.0, 0.0 → 地番の点（欠損を示す値）")),
        ("位置レベル8の点が無ければ空欄にする",
         decide_coord("43.0", "141.0",
                      {"ID": "H004", "座標の出典": "なし", "元_緯度": "43.0", "元_経度": "141.0",
                       "座標の理由": "元データの座標 43.0, 141.0 を別の市区町村の施設と共有しているため使わない",
                       "住所_lat": "43.06", "住所_lon": "141.35", "住所_位置レベル": "3"},
                      None),
         ("", "", "",
          "空欄にした: 緯度経度 43.0, 141.0（別の市区町村の施設と共有している。位置レベル8の住所の点が無い）")),
        ("町字の代表点で県外の座標を置き換えた行は、地番の点を使う",
         decide_coord("34.0", "135.0",
                      {"ID": "H005", "座標の出典": "ジオコーディング", "元_緯度": "34.0",
                       "元_経度": "135.0",
                       "座標の理由": "元データの座標 34.0, 135.0 が北海道ではなく大阪府と兵庫県の範囲にあるため、ジオコーダ座標を採用",
                       "住所_lat": "43.3", "住所_lon": "141.6", "住所_位置レベル": "3"},
                      ("43.4", "141.7")),
         ("43.4", "141.7", "地番",
          "書き換えた: 緯度経度 34.0, 135.0 → 地番の点（北海道ではなく大阪府と兵庫県の範囲にある）")),
        ("住所の点から離れた座標は、距離を注記に書く",
         decide_coord("43.2", "141.5",
                      {"ID": "H006", "座標の出典": "ジオコーディング", "元_緯度": "43.2",
                       "元_経度": "141.5",
                       "座標の理由": "元データの座標 43.2, 141.5 がジオコーダ座標から1,523m離れているため、ジオコーダ座標を採用",
                       "住所_lat": "43.21", "住所_lon": "141.51", "住所_位置レベル": "8"},
                      None),
         ("43.21", "141.51", "住居表示",
          "書き換えた: 緯度経度 43.2, 141.5 → 住居表示の点（住所の点から1,523m離れている）")),
        ("格子に乗る丸め値は、末尾の「の」を落として書く",
         decide_coord("38", "140",
                      {"ID": "H007", "座標の出典": "なし", "元_緯度": "38", "元_経度": "140",
                       "座標の理由": "元データの座標 38, 140 が1度の格子に乗る丸め値のため使わない",
                       "住所_lat": "", "住所_lon": "", "住所_位置レベル": ""},
                      None),
         ("", "", "",
          "空欄にした: 緯度経度 38, 140（1度の格子に乗る丸め値。位置レベル8の住所の点が無い）")),
    ]

    failed = 0
    print("=== corrected_rules.py 逆テスト ===\n")
    for name, got, want in cases:
        ok = got == want
        if not ok:
            failed += 1
        print(f"  {'PASS' if ok else 'FAIL'}  {name}")
        if not ok:
            print(f"        実際: {got}")
            print(f"        期待: {want}")
    print(f"\n  {len(cases) - failed}/{len(cases)} 件")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
